#!/usr/bin/env bash
# Re-arm the deploy chain after the 2026-11-13 08:12Z container recreation wiped
# the gitignored runtime state (.env keys + db/production-mirror-latest.json).
# That unarmed state is exactly what made the DATA-SAFETY deploy gate fail the
# user's Deploy ("Sorry, there was a problem deploying the code").
#
# Restores (values never printed):
#   .env  DATABASE_URL                  (keep the boot-written value)
#   .env  DISCORD_CLIENT_ID             1552617559675633664 — public OAuth client id,
#                                       recovered from the production authorize
#                                       redirect (worklog 1229/1270 precedent)
#   .env  DB_MIRROR_EXPORT_KEY          NEW random 64-hex (old key died with the
#                                       old container; regen is the documented
#                                       procedure — worklog line 1270)
#   .env  SMTP_HOST/PORT/USER/PASS      copied silently from the /tmp/my-project
#                                       snapshot (.env) — the exact creds that
#                                       verified Gmail AUTH 235 at 05:00Z
#   .env  DISCORD_CLIENT_SECRET         left EMPTY (unrecoverable by design;
#                                       PKCE-only path is validated working)
#   db/production-mirror-latest.json    armed from the current workspace mirror
#                                       (honest empty state — prod containers
#                                       are dead, their data unrecoverable)
set -euo pipefail

PROJECT=/home/z/my-project
SNAPSHOT_ENV=/tmp/my-project/.env
ENV_FILE="$PROJECT/.env"

# --- 1. rebuild .env ---------------------------------------------------------
TMP_ENV=$(mktemp)
trap 'rm -f "$TMP_ENV"' EXIT

{
  echo "# Runtime config — regenerated by scripts/restore_deploy_env.sh (2026-11-13)"
  echo "# after the 08:12Z container recreation wiped the gitignored runtime state."
  echo "DATABASE_URL=file:$PROJECT/db/custom.db"
  echo "# Public OAuth client id (== application id); secret intentionally absent (PKCE)."
  echo "DISCORD_CLIENT_ID=1552617559675633664"
  echo "# 64-hex key for the deploy-time account/session mirror round-trip."
  echo "DB_MIRROR_EXPORT_KEY=$(node -e 'console.log(require("crypto").randomBytes(32).toString("hex"))')"
  # SMTP creds: pull silently from the snapshot, never echo the values.
  if [ -f "$SNAPSHOT_ENV" ]; then
    for k in SMTP_HOST SMTP_PORT SMTP_USER SMTP_PASS MAIL_FROM; do
      v=$(grep -E "^$k=" "$SNAPSHOT_ENV" | tail -1 | cut -d= -f2- || true)
      [ -n "$v" ] && echo "$k=$v"
    done
  fi
} > "$TMP_ENV"

mv "$TMP_ENV" "$ENV_FILE"
chmod 600 "$ENV_FILE"
trap - EXIT

# --- 2. verify keys without printing values ----------------------------------
echo "--- .env keys restored ---"
grep -oE '^[A-Z_]+' "$ENV_FILE"
MISSING=0
for k in DATABASE_URL DISCORD_CLIENT_ID DB_MIRROR_EXPORT_KEY SMTP_HOST SMTP_PORT SMTP_USER SMTP_PASS; do
  grep -qE "^$k=..*" "$ENV_FILE" || { echo "MISSING: $k"; MISSING=1; }
done
[ "$MISSING" = "0" ] || { echo "FAILED to restore all keys"; exit 1; }

# --- 3. re-arm the deploy-time mirror cache ----------------------------------
MIRROR="$PROJECT/db/db-mirror.json"
CACHE="$PROJECT/db/production-mirror-latest.json"
python3 - "$MIRROR" << 'PYEOF'
import json, sys
with open(sys.argv[1]) as f:
    data = json.load(f)
tables = data.get("tables")
assert isinstance(tables, dict) and len(tables) >= 10, "mirror missing tables"
print("mirror OK: savedAt=%s, tables=%d" % (data.get("savedAt"), len(tables)))
print("accounts:", len(tables.get("account") or []), "systemKeys:", len(tables.get("systemKey") or []))
PYEOF
cp "$MIRROR" "$CACHE"
chmod 600 "$CACHE"
echo "armed: $CACHE ($(stat -c %s "$CACHE") bytes)"
echo "DEPLOY CHAIN RE-ARMED"
